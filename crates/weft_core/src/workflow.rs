//! Parameterized command workflows (v0.7 "Stitch").
//!
//! A [`Workflow`] is a named, reusable command template with `{{var}}`
//! placeholders. Users define workflows via the Command Palette or YAML
//! import; at runtime, variables are filled in via a form and the rendered
//! commands are submitted to the shell.
//!
//! ## Architecture
//!
//! - **Data model**: [`Workflow`] / [`WorkflowStep`] / [`WorkflowVar`] /
//!   [`WorkflowSource`] — pure data, fully serializable (serde + YAML).
//! - **Render engine**: [`Workflow::render`] replaces `{{var}}` with
//!   user-supplied values; [`Workflow::extract_var_names`] scans command
//!   templates for variables.
//! - **Persistence**: [`WorkflowStore`] wraps a SQLite connection (mirroring
//!   `persistence::BlockStore`). Workflows are the source-of-truth in the DB;
//!   YAML is only for import/export.

use std::collections::HashMap;
use std::path::Path;

use rusqlite::{params, Connection};
use serde::{Deserialize, Serialize};

// ── Data model ────────────────────────────────────────────────────────

/// Where a workflow originated. `Ai` is a forward-looking tag for v0.6
/// (AI-generated workflows); it has no behavioral effect today.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum WorkflowSource {
    /// User-created or imported from YAML.
    #[default]
    #[serde(rename = "manual")]
    Manual,
    /// Generated by an AI backend (v0.6+).
    #[serde(rename = "ai")]
    Ai,
}

/// A single variable definition within a workflow.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct WorkflowVar {
    pub name: String,
    pub description: String,
    #[serde(default)]
    pub default: Option<String>,
    #[serde(default = "default_true")]
    pub required: bool,
}

fn default_true() -> bool {
    true
}

/// One command step in a workflow. A workflow may have multiple steps
/// executed sequentially. The `command` string may contain `{{var}}`
/// placeholders.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct WorkflowStep {
    pub command: String,
}

/// A complete workflow definition — the unit of persistence and the data
/// behind the Command Palette workflow entries.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Workflow {
    /// SQLite primary key. 0 for unsaved/new workflows.
    #[serde(default)]
    pub id: i64,
    /// Unique short name used as the Command Palette search key (e.g. "deploy").
    pub name: String,
    /// Human-readable description shown in the palette.
    #[serde(default)]
    pub description: String,
    /// Ordered command steps. Variables are shared across all steps.
    #[serde(default)]
    pub steps: Vec<WorkflowStep>,
    /// Declared variables. If empty, [`extract_var_names`] is used to
    /// auto-discover `{{var}}` placeholders from the steps.
    #[serde(default)]
    pub variables: Vec<WorkflowVar>,
    /// Origin (manual or AI).
    #[serde(default)]
    pub source: WorkflowSource,
    /// How many times this workflow has been run (for palette sort order).
    #[serde(default)]
    pub use_count: i64,
    /// Last-run timestamp (Unix epoch millis).
    #[serde(default)]
    pub last_used_ms: i64,
}

// ── Render engine ────────────────────────────────────────────────────

/// Variable substitution failure.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum RenderError {
    #[error("missing required variable: {{{{{0}}}}}")]
    MissingRequired(String),
}

impl Workflow {
    /// Replace all `{{var}}` placeholders in every step with values from
    /// `values`. Resolution priority: `values` → `default` → error (if
    /// `required`) → empty string (if not required).
    ///
    /// Returns one rendered command string per step, in order.
    pub fn render(&self, values: &HashMap<String, String>) -> Result<Vec<String>, RenderError> {
        // First pass: check that every required DECLARED variable has a value.
        for var in &self.variables {
            let has_value = values.contains_key(&var.name) || var.default.is_some();
            if !has_value && var.required {
                return Err(RenderError::MissingRequired(var.name.clone()));
            }
        }

        // Build a lookup of declared variable defaults (name → default).
        let declared_defaults: HashMap<&str, Option<&str>> = self
            .variables
            .iter()
            .map(|v| (v.name.as_str(), v.default.as_deref()))
            .collect();

        // Second pass: replace ALL {{var}} in each step — both declared and
        // discovered (from the command text). This handles workflows created
        // via the UI editor which store variables: vec![] but have {{var}}
        // placeholders in their commands.
        let mut rendered = Vec::with_capacity(self.steps.len());
        for step in &self.steps {
            let mut cmd = step.command.clone();
            // Collect all var names that appear in this step's command.
            let var_names = {
                let mut names = Vec::new();
                scan_var_names(&step.command, &mut names);
                names
            };
            for name in &var_names {
                let val = values
                    .get(name)
                    .cloned()
                    .or_else(|| {
                        declared_defaults
                            .get(name.as_str())
                            .and_then(|d| d.map(String::from))
                    })
                    .unwrap_or_default();
                cmd = cmd.replace(&format!("{{{{{}}}}}", name), &val);
            }
            rendered.push(cmd);
        }
        Ok(rendered)
    }

    /// Extract all `{{var}}` names from the step commands. Used to auto-generate
    /// the variable form when `self.variables` is empty or incomplete.
    pub fn extract_var_names(&self) -> Vec<String> {
        let mut names: Vec<String> = Vec::new();
        for step in &self.steps {
            scan_var_names(&step.command, &mut names);
        }
        names
    }

    /// All variable names that need a form field: declared variables first
    /// (preserving their order/metadata), then any undiscovered `{{var}}`
    /// placeholders not in the declared list.
    pub fn all_var_names(&self) -> Vec<String> {
        let declared: Vec<String> = self.variables.iter().map(|v| v.name.clone()).collect();
        let mut all = declared.clone();
        for discovered in self.extract_var_names() {
            if !all.contains(&discovered) {
                all.push(discovered);
            }
        }
        all
    }
}

/// Scan `text` for `{{name}}` patterns, appending unique names to `out`.
fn scan_var_names(text: &str, out: &mut Vec<String>) {
    let bytes = text.as_bytes();
    let mut i = 0;
    while i + 1 < bytes.len() {
        if bytes[i] == b'{' && bytes[i + 1] == b'{' {
            // Find the closing }}.
            if let Some(end) = text[i + 2..].find("}}") {
                let name = text[i + 2..i + 2 + end].trim().to_string();
                if !name.is_empty() && !out.contains(&name) {
                    out.push(name);
                }
                i = i + 2 + end + 2;
                continue;
            }
        }
        i += 1;
    }
}

// ── WorkflowStore (SQLite persistence) ───────────────────────────────

/// Errors from the workflow store: filesystem or SQLite.
#[derive(Debug, thiserror::Error)]
pub enum WorkflowStoreError {
    #[error("io error: {0}")]
    Io(#[from] std::io::Error),
    #[error("sqlite error: {0}")]
    Sqlite(#[from] rusqlite::Error),
    #[error("json error: {0}")]
    Json(#[from] serde_json::Error),
    #[error("yaml error: {0}")]
    Yaml(#[from] serde_yaml_ng::Error),
}

/// SQLite-backed store of workflow definitions. Mirrors `BlockStore` in
/// design: one `rusqlite::Connection`, idempotent schema, synchronous I/O.
pub struct WorkflowStore {
    conn: Connection,
}

const SCHEMA: &str = "\
CREATE TABLE IF NOT EXISTS workflows (\
    id             INTEGER PRIMARY KEY AUTOINCREMENT,\
    name           TEXT NOT NULL UNIQUE,\
    description    TEXT NOT NULL DEFAULT '',\
    steps_json     TEXT NOT NULL,\
    variables_json TEXT NOT NULL,\
    source         TEXT NOT NULL DEFAULT 'manual',\
    use_count      INTEGER NOT NULL DEFAULT 0,\
    last_used_ms   INTEGER NOT NULL DEFAULT 0,\
    created_ms     INTEGER NOT NULL DEFAULT 0\
);\
CREATE INDEX IF NOT EXISTS idx_workflows_name ON workflows(name);\
CREATE INDEX IF NOT EXISTS idx_workflows_use ON workflows(use_count DESC, last_used_ms DESC);";

impl WorkflowStore {
    /// Open (creating if needed) the workflow DB at `path`.
    pub fn open(path: &Path) -> Result<Self, WorkflowStoreError> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let conn = Connection::open(path)?;
        conn.execute_batch(SCHEMA)?;
        Ok(Self { conn })
    }

    /// Insert a new workflow. Returns the assigned `id`.
    pub fn insert(&self, wf: &Workflow) -> Result<i64, WorkflowStoreError> {
        let steps_json = serde_json::to_string(&wf.steps)?;
        let variables_json = serde_json::to_string(&wf.variables)?;
        let source = match wf.source {
            WorkflowSource::Manual => "manual",
            WorkflowSource::Ai => "ai",
        };
        let created_ms = current_millis();
        self.conn.execute(
            "INSERT INTO workflows (name, description, steps_json, variables_json, source, use_count, last_used_ms, created_ms) \
             VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8)",
            params![
                &wf.name,
                &wf.description,
                &steps_json,
                &variables_json,
                source,
                wf.use_count,
                wf.last_used_ms,
                created_ms,
            ],
        )?;
        Ok(self.conn.last_insert_rowid())
    }

    /// Update an existing workflow by id.
    pub fn update(&self, wf: &Workflow) -> Result<(), WorkflowStoreError> {
        let steps_json = serde_json::to_string(&wf.steps)?;
        let variables_json = serde_json::to_string(&wf.variables)?;
        let source = match wf.source {
            WorkflowSource::Manual => "manual",
            WorkflowSource::Ai => "ai",
        };
        self.conn.execute(
            "UPDATE workflows SET name=?2, description=?3, steps_json=?4, variables_json=?5, source=?6 \
             WHERE id=?1",
            params![
                wf.id,
                &wf.name,
                &wf.description,
                &steps_json,
                &variables_json,
                source,
            ],
        )?;
        Ok(())
    }

    /// Delete by id.
    pub fn delete(&self, id: i64) -> Result<(), WorkflowStoreError> {
        self.conn
            .execute("DELETE FROM workflows WHERE id=?1", params![id])?;
        Ok(())
    }

    /// Find by unique name.
    ///
    /// v1.12.25 (audit 3-B, P1-05): a real DB error is now `Err` — the old
    /// `.ok()` collapsed it into `Ok(None)`, indistinguishable from "no such
    /// workflow". Callers can tell "absent" from "read failed".
    pub fn find_by_name(&self, name: &str) -> Result<Option<Workflow>, WorkflowStoreError> {
        let mut stmt = self.conn.prepare(
            "SELECT id, name, description, steps_json, variables_json, source, use_count, last_used_ms \
             FROM workflows WHERE name=?1",
        )?;
        match stmt.query_row(params![name], row_to_workflow) {
            Ok(row) => Ok(Some(row)),
            Err(rusqlite::Error::QueryReturnedNoRows) => Ok(None),
            Err(e) => Err(e.into()),
        }
    }

    /// List all workflows, sorted by use frequency (most-used first).
    pub fn list(&self) -> Result<Vec<Workflow>, WorkflowStoreError> {
        let mut stmt = self.conn.prepare(
            "SELECT id, name, description, steps_json, variables_json, source, use_count, last_used_ms \
             FROM workflows ORDER BY use_count DESC, last_used_ms DESC, name ASC",
        )?;
        let rows = stmt.query_map([], row_to_workflow)?;
        rows.collect::<Result<Vec<_>, _>>().map_err(Into::into)
    }

    /// Case-insensitive substring search on name or description.
    pub fn search(&self, query: &str, limit: usize) -> Result<Vec<Workflow>, WorkflowStoreError> {
        // INSTR does a literal substring match (not LIKE pattern), so no % wildcards.
        let mut stmt = self.conn.prepare(
            "SELECT id, name, description, steps_json, variables_json, source, use_count, last_used_ms \
             FROM workflows \
             WHERE INSTR(LOWER(name), LOWER(?1)) > 0 OR INSTR(LOWER(description), LOWER(?1)) > 0 \
             ORDER BY use_count DESC, last_used_ms DESC LIMIT ?2",
        )?;
        let rows = stmt.query_map(params![query, limit as i64], row_to_workflow)?;
        rows.collect::<Result<Vec<_>, _>>().map_err(Into::into)
    }

    /// Increment use count and update last_used_ms.
    pub fn bump_use_count(&self, id: i64) -> Result<(), WorkflowStoreError> {
        self.conn.execute(
            "UPDATE workflows SET use_count = use_count + 1, last_used_ms = ?2 WHERE id=?1",
            params![id, current_millis()],
        )?;
        Ok(())
    }

    /// Total number of stored workflows (for seed-data detection).
    pub fn count(&self) -> Result<i64, WorkflowStoreError> {
        let count: i64 = self
            .conn
            .query_row("SELECT COUNT(*) FROM workflows", [], |row| row.get(0))?;
        Ok(count)
    }

    // ── YAML import / export ──────────────────────────────────────────

    /// Import a workflow from YAML text. Creates a new workflow or updates
    /// an existing one if the name matches. Returns the workflow id.
    pub fn import_yaml(&self, yaml: &str) -> Result<i64, WorkflowStoreError> {
        let wf: Workflow = serde_yaml_ng::from_str(yaml)?;
        // Check if a workflow with this name already exists.
        if let Some(existing) = self.find_by_name(&wf.name)? {
            let mut updated = wf.clone();
            updated.id = existing.id;
            self.update(&updated)?;
            Ok(existing.id)
        } else {
            self.insert(&wf)
        }
    }

    /// Export a workflow as YAML text.
    pub fn export_yaml(&self, id: i64) -> Result<String, WorkflowStoreError> {
        let mut stmt = self.conn.prepare(
            "SELECT id, name, description, steps_json, variables_json, source, use_count, last_used_ms \
             FROM workflows WHERE id=?1",
        )?;
        let wf = stmt.query_row(params![id], row_to_workflow)?;
        Ok(serde_yaml_ng::to_string(&wf)?)
    }
}

/// Decode a SQLite row into a [`Workflow`].
fn row_to_workflow(row: &rusqlite::Row) -> rusqlite::Result<Workflow> {
    let id: i64 = row.get(0)?;
    let name: String = row.get(1)?;
    let description: String = row.get(2)?;
    let steps_json: String = row.get(3)?;
    let variables_json: String = row.get(4)?;
    let source_str: String = row.get(5)?;
    let use_count: i64 = row.get(6)?;
    let last_used_ms: i64 = row.get(7)?;

    let steps: Vec<WorkflowStep> = serde_json::from_str(&steps_json).unwrap_or_default();
    let variables: Vec<WorkflowVar> = serde_json::from_str(&variables_json).unwrap_or_default();
    let source = match source_str.as_str() {
        "ai" => WorkflowSource::Ai,
        _ => WorkflowSource::Manual,
    };

    Ok(Workflow {
        id,
        name,
        description,
        steps,
        variables,
        source,
        use_count,
        last_used_ms,
    })
}

/// Current Unix epoch millis.
fn current_millis() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

